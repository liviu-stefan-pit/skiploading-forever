// Builds Seed.lua for Skip Loading from the GatherMate2_Data files, without touching them.
//   node build-seed.js
// Only mining and herbalism are imported. Points of the same node type that sit next to each
// other (the same node reported at slightly different coordinates) are merged into one.
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "..", "GatherMate2_Data");
const FLAVOR = "Forever";
const OUT = path.join(__dirname, "..", "Seed.lua");
// Coordinates are in units of 0.01% of the map. The source data sits on a 0.1% grid, so 23
// merges a point with its neighbours up to two cells away, and leaves real separate spawns alone.
const MERGE = 23;

function parse(file) {
  const zones = {};
  let zone = null;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    let m;
    if ((m = line.match(/^\t\[(\d+)\] = \{/))) zones[(zone = m[1])] = [];
    else if ((m = line.match(/^\t\t\[(\d+)\] = (\d+),/))) {
      const c = Number(m[1]);
      zones[zone].push({ x: Math.floor(c / 1e6), y: Math.floor((c % 1e6) / 100), id: Number(m[2]) });
    }
  }
  return zones;
}

function merge(points) {
  const clusters = [];
  points.sort((a, b) => a.id - b.id || a.x - b.x || a.y - b.y);
  for (const p of points) {
    let best = null, bestD = MERGE;
    for (const c of clusters) {
      if (c.id !== p.id) continue;
      const d = Math.hypot(c.sx / c.n - p.x, c.sy / c.n - p.y);
      if (d <= bestD) { best = c; bestD = d; }
    }
    if (best) { best.sx += p.x; best.sy += p.y; best.n++; }
    else clusters.push({ id: p.id, sx: p.x, sy: p.y, n: 1 });
  }
  return clusters.map(c => ({ id: c.id, x: Math.round(c.sx / c.n), y: Math.round(c.sy / c.n) }));
}

function emit(name, zones, stats) {
  let out = `\t${name} = {\n`;
  for (const zone of Object.keys(zones).sort((a, b) => a - b)) {
    const merged = merge(zones[zone]);
    stats.before += zones[zone].length;
    stats.after += merged.length;
    const used = new Set();
    const cells = merged.sort((a, b) => a.x - b.x || a.y - b.y).map(p => {
      let key = p.x * 1e6 + p.y * 100;
      while (used.has(key)) key++; // two node types on the same spot share a coordinate
      used.add(key);
      return `[${key}]=${p.id}`;
    });
    out += `\t\t[${zone}] = {\n`;
    for (let i = 0; i < cells.length; i += 8) out += `\t\t\t${cells.slice(i, i + 8).join(",")},\n`;
    out += `\t\t},\n`;
  }
  return out + `\t},\n`;
}

const toc = fs.readFileSync(path.join(SRC, "GatherMate2_Data_Mainline.toc"), "utf8");
const version = (toc.match(/## Version: (\S+)/) || [])[1] || "unknown";
const ores = { before: 0, after: 0 }, herbs = { before: 0, after: 0 };
const body =
  emit("ores", parse(path.join(SRC, FLAVOR, "MiningData.lua")), ores) +
  emit("herbs", parse(path.join(SRC, FLAVOR, "HerbalismData.lua")), herbs);

fs.writeFileSync(OUT,
  `-- Generated by tools/build-seed.js from GatherMate2_Data ${version} (${FLAVOR}). Do not edit.\n` +
  `-- Used once, to create SkipLoadingForeverDataSet the first time the addon loads.\n` +
  `-- Key = x * 1000000 + y * 100 + slot, x and y in 0.01% of the map. Value = node id.\n` +
  `SkipLoadingSeed = function() return {\n` +
  `\tversion = 1,\n\tsource = "GatherMate2_Data ${version} (${FLAVOR})",\n` +
  body + `} end\n`);

console.log(`ores:  ${ores.before} -> ${ores.after}`);
console.log(`herbs: ${herbs.before} -> ${herbs.after}`);
console.log(`wrote ${OUT} (${fs.statSync(OUT).size} bytes)`);
